"""Measured alpha-bound extraction and ordinary icon encoding; never edits masters."""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label,find_objects
root=Path(__file__).resolve().parents[1]
manifest={}
tiers=['beginner','copper','iron','gold','mythril','dragon','shadow']
slots=['head','chest','legs','feet','offhand','neck','ring','sword','bow','staff','daggers']
legacy=['clothHood','clothTunic','clothTrousers','leatherBoots','woodenShield','beginnerPendant','beginnerRing','sword','bow','wand','dagger']
suffix=['Helm','Armor','Greaves','Boots','Shield','Pendant','Ring','Sword','Bow','Staff','Daggers']
for tier in tiers:
 path=root/'assets/equipment/masters'/f'{tier}.png'
 image=Image.open(path).convert('RGBA');w,h=image.size;a=np.asarray(image)[:,:,3]
 components,n=label(a>32);boxes=[[] for _ in range(12)]
 for i,sl in enumerate(find_objects(components),1):
  if sl is None or np.count_nonzero(components[sl]==i)<12:continue
  yy,xx=sl;cx=(xx.start+xx.stop)/2;cy=(yy.start+yy.stop)/2
  index=min(2,int(cy/h*3))*4+min(3,int(cx/w*4));boxes[index].append((xx.start,yy.start,xx.stop,yy.stop))
 frames={}
 for i,name in enumerate(slots):
  assert boxes[i],(tier,name)
  x=max(0,min(b[0] for b in boxes[i])-2);y=max(0,min(b[1] for b in boxes[i])-2);right=min(w,max(b[2] for b in boxes[i])+2);bottom=min(h,max(b[3] for b in boxes[i])+2)
  id=legacy[i] if tier=='beginner' else ['knightSword','archerBow','mageStaff','rogueDaggers'][i-7] if tier=='copper' and i>=7 else tier+suffix[i]
  crop=image.crop((x,y,right,bottom));crop.thumbnail((112,112),Image.Resampling.LANCZOS)
  icon=Image.new('RGBA',(128,128));icon.alpha_composite(crop,((128-crop.width)//2,(128-crop.height)//2));icon.save(root/'assets/items'/f'{id}.png',optimize=True)
  scale=min(56/(right-x),56/(bottom-y));dw=(right-x)*scale;dh=(bottom-y)*scale
  frames['doll-item-'+id]={'source':[x,y,right-x,bottom-y],'size':[64,64],'placement':[(64-dw)/2,(64-dh)/2,dw,dh]}
 if tier!='beginner':
  for slot in ['chest','legs','feet']:
   i=slots.index(slot);id=tier+suffix[i];x,y,sw,sh=frames['doll-item-'+id]['source']
   if slot=='chest':
    for view in ['front','side','back']:
     frames['gear-'+id+'-'+view]={'source':[x,y,sw,sh],'size':[44,46],'placement':[10 if view=='side' else 0,0,24 if view=='side' else 44,46]}
    frames['gear-'+id+'-sleeve']={'source':[x,y,sw*.25,sh*.35],'size':[18,45],'placement':[0,0,18,16]}
   else:
    for foot in range(2):
     for view in (['front','side','back'] if slot=='feet' else ['front']):
      size=[22,19] if slot=='feet' else [20,38]
      frames['gear-'+id+'-'+str(foot)+'-'+view]={'source':[x+sw*foot/2,y,sw/2,sh],'size':size,'placement':[4 if view=='side' else 0,0,size[0]-8 if view=='side' else size[0],size[1]]}
 image.save(root/'assets/equipment'/f'{tier}.webp',quality=95,method=6)
 manifest[tier]=frames
print('Extracted 77 alpha-trimmed icons and seven runtime atlases')
(root/'apps/client/src/equipment-frames.ts').write_text('// Measured alpha bounds; generated by scripts/extract-equipment-sprites.py.\nimport type {GeneratedFrame} from \'./generated-frames\';\nexport const equipmentFrames:Record<string,Record<string,GeneratedFrame>>='+json.dumps(manifest,separators=(',',':'))+';\n')
